// 002 Arithmetic operations in Java

public class Main {
    public static void main(String[] details) {
        System.out.println("7+2=" + (7+2));
        System.out.println("7-2=" + (7-2));
        System.out.println("7*2=" + (7*2));
        System.out.println("7/2=" + (7/2));
        System.out.println("7%2=" + (7%2));
    }
}
